"""Приблизительный перевод русского адреса на украинский — запасной вариант для поиска.

Nominatim и так находит улицы по русским названиям, если они внесены в OpenStreetMap (name:ru).
Но у части улиц русского названия в базе нет, и «Пушкинская 10» не находится,
хотя «Пушкінська 10» — находится. Тогда пробуем второй запрос, переделанный этим модулем:
словарь частых слов (типы улиц, города области) + регулярные окончания прилагательных.
Это эвристика, а не переводчик: цель — чтобы второй запрос чаще попадал, а не был идеальным.
"""

import re

WORDS = {
    # Типы улиц
    "улица": "вулиця",
    "ул": "вул",
    "переулок": "провулок",
    "пер": "пров",
    "площадь": "площа",
    "шоссе": "шосе",
    "набережная": "набережна",
    "проезд": "проїзд",
    "въезд": "в'їзд",
    "спуск": "узвіз",
    "микрорайон": "мікрорайон",
    # Населённые пункты Харьковской области
    "харьков": "харків",
    "харьковская": "харківська",
    "харьковский": "харківський",
    "чугуев": "чугуїв",
    "изюм": "ізюм",
    "купянск": "куп'янськ",
    "лозовая": "лозова",
    "балаклея": "балаклія",
    "богодухов": "богодухів",
    "змиев": "зміїв",
    "дергачи": "дергачі",
    "волчанск": "вовчанськ",
    "барвенково": "барвінкове",
    "пивденное": "південне",
    "солоницевка": "солоницівка",
    "песочин": "пісочин",
    "рогань": "рогань",
    # Частые слова в названиях улиц
    "героев": "героїв",
    "труда": "праці",
    "академика": "академіка",
    "независимости": "незалежності",
    "победы": "перемоги",
}

# Окончания прилагательных: Клочковская → Клочківська, Пушкинская → Пушкінська, Сумская → Сумська.
# Порядок важен: длинные окончания раньше коротких.
ENDINGS = [
    ("овская", "івська"),
    ("овский", "івський"),
    ("евская", "івська"),
    ("евский", "івський"),
    ("инская", "інська"),
    ("инский", "інський"),
    ("цкая", "цька"),
    ("цкий", "цький"),
    ("ская", "ська"),
    ("ский", "ський"),
    ("ная", "на"),
    ("ный", "ний"),
]

LETTERS = str.maketrans({"ы": "и", "э": "е", "ё": "е", "ъ": "'"})

_WORD = re.compile(r"[А-Яа-яЁёІіЇїЄєҐґ']+")


def _ukrainize_word(match: re.Match) -> str:
    word = match.group(0)
    lower = word.lower()
    if lower in WORDS:
        result = WORDS[lower]
    else:
        result = lower
        for ru, uk in ENDINGS:
            if result.endswith(ru) and len(result) > len(ru) + 1:
                result = result[: -len(ru)] + uk
                break
        result = result.translate(LETTERS)
    if result == lower:
        return word
    return result[0].upper() + result[1:] if word[0].isupper() else result


def ukrainize(text: str) -> str:
    """«Харьков, ул. Клочковская 5» → «Харків, вул. Клочківська 5». Украинский текст не меняется."""
    return _WORD.sub(_ukrainize_word, text)
